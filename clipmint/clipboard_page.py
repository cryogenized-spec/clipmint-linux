"""Construct the clipboard archive and generic information pages."""
from __future__ import annotations
from PySide6.QtCore import Qt
from PySide6.QtWidgets import (
    QComboBox, QFrame, QHBoxLayout, QLabel, QLineEdit, QListWidget,
    QPushButton, QStackedWidget, QTabBar, QVBoxLayout, QWidget,
)
from .history_filters import populate_filter_tabs
from .library_controller import ImagePreviewLabel

def build_clipboard_page(w):
    page = QWidget()
    layout = QVBoxLayout(page)
    layout.setContentsMargins(0, 0, 0, 0)
    layout.setSpacing(12)
    bins = QHBoxLayout()
    w.tabs = QTabBar()
    w.tabs.setExpanding(True)
    w.tabs.setDrawBase(False)
    # Tabs filter a unified history; none represents a storage folder.
    populate_filter_tabs(w.tabs)
    w.tabs.currentChanged.connect(w.refresh)
    bins.addWidget(w.tabs, 1)
    layout.addLayout(bins)
    w.search = QLineEdit()
    w.search.setPlaceholderText("Search all copied content…")
    w.search.textChanged.connect(w._schedule_history_search)
    layout.addWidget(w.search)
    sorts = QHBoxLayout()
    sorts.addWidget(QLabel("Collection:"))
    w.bin_filter = QComboBox()
    w.bin_filter.setObjectName("collectionFilter")
    w.bin_filter.addItem("All collections", None)
    for name in w.store.bins():
        w.bin_filter.addItem(name, name)
    w.bin_filter.currentIndexChanged.connect(w.refresh)
    sorts.addWidget(w.bin_filter)
    add_bin = QPushButton("+")
    add_bin.setToolTip("Create an Autosort collection")
    add_bin.clicked.connect(w.new_bin)
    sorts.addWidget(add_bin)
    sorts.addWidget(QLabel("Sort:"))
    w.sort_combo = QComboBox()
    w.sort_combo.addItems(["Latest first", "Oldest first", "A–Z", "Z–A", "Best match", "Numbered list"])
    w.sort_combo.currentIndexChanged.connect(w.refresh)
    sorts.addWidget(w.sort_combo)
    sorts.addStretch()
    layout.addLayout(sorts)
    w.count_label = QLabel("Clipboard")
    w.count_label.setObjectName("sectionTitle")
    layout.addWidget(w.count_label)
    middle = QHBoxLayout()
    middle.setSpacing(12)
    w.history = QListWidget()
    w.history.setContextMenuPolicy(Qt.ContextMenuPolicy.CustomContextMenu)
    w.history.customContextMenuRequested.connect(w.context_menu)
    w.history.itemDoubleClicked.connect(w.copy_clip)
    w.history.currentItemChanged.connect(w.preview_clip)
    middle.addWidget(w.history, 4)
    preview_frame = QFrame()
    preview_frame.setObjectName("preview")
    preview_frame.setMinimumWidth(185)
    preview_frame.setMaximumWidth(290)
    right = QVBoxLayout(preview_frame)
    w.preview_heading = QLabel("PREVIEW  /  プレビュー")
    w.preview_heading.setObjectName("previewHeading")
    right.addWidget(w.preview_heading)
    w.preview_stack = QStackedWidget()
    w.preview_label = QLabel("Select an item to preview")
    w.preview_label.setWordWrap(True)
    w.preview_label.setAlignment(Qt.AlignmentFlag.AlignTop)
    w.preview_label.setTextInteractionFlags(Qt.TextInteractionFlag.TextSelectableByMouse)
    w.preview_stack.addWidget(w.preview_label)
    w.preview_image_page = QWidget()
    image_layout = QVBoxLayout(w.preview_image_page)
    image_layout.setContentsMargins(0, 0, 0, 0)
    w.preview_image = ImagePreviewLabel()
    image_layout.addWidget(w.preview_image, 1)
    w.preview_dimensions = QLabel("")
    w.preview_dimensions.setObjectName("previewDimensions")
    w.preview_dimensions.setAlignment(Qt.AlignmentFlag.AlignCenter)
    image_layout.addWidget(w.preview_dimensions)
    w.preview_stack.addWidget(w.preview_image_page)
    right.addWidget(w.preview_stack, 1)
    copy = QPushButton("Copy selected")
    copy.clicked.connect(w.copy_selected)
    right.addWidget(copy)
    middle.addWidget(preview_frame, 2)
    layout.addLayout(middle, 1)
    w.pages.addWidget(page)

def build_info_page(w, title: str, description: str):
    page = QWidget()
    layout = QVBoxLayout(page)
    heading = QLabel(title)
    heading.setObjectName("sectionTitle")
    layout.addWidget(heading)
    label = QLabel(description)
    label.setWordWrap(True)
    label.setAlignment(Qt.AlignmentFlag.AlignTop)
    label.setStyleSheet("font-size:14px;")
    layout.addWidget(label)
    layout.addStretch()
    w.pages.addWidget(page)
